export function translate(lang: UiLang, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = (lang === 'hi' ? hi[key] : undefined) ?? en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export type Translator = (key: MessageKey, vars?: Record<string, string | number>) => string;

/**
 * Typed lookups for keys built from data (decision status, class number).
 * Keeps the `t()` call site honest without `as` casts sprinkled through screens.
 */
export function decisionKey(status: string): MessageKey {
  const key = `decision.${status}`;
  return (key in en ? key : 'decision.provisional') as MessageKey;
}

export function decisionSubKey(status: string): MessageKey {
  const key = `decision.${status}.sub`;
  return (key in en ? key : 'decision.provisional.sub') as MessageKey;
}

export function classKey(klass: 1 | 2 | 3): MessageKey {
  return `onboarding.class${klass}` as MessageKey;
}
